/**
 * Formats an integer amount in cents as South African rand without floating-point arithmetic.
 * Returns "Not reported" for missing or unsafe values rather than a guessed figure.
 */
export function formatZarCents(cents: number | null | undefined): string {
  if (cents === null || cents === undefined || !Number.isSafeInteger(cents)) return "Not reported";
  const sign = cents < 0 ? "-" : "";
  const absolute = Math.abs(cents);
  const rands = Math.floor(absolute / 100);
  const remainder = absolute % 100;
  return `${sign}R ${rands.toLocaleString("en-ZA")},${String(remainder).padStart(2, "0")}`;
}
